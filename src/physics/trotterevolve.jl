function trotterstep!(pepo::PEPO)
    bonds = getbonds(pepo; reverse=istransposed(pepo))

    _trotterstep!(pepo, bonds[1])

    renormalize!(environment, pepo; renormalization=:full)
    # Switch axis
    transpose!(pepo)
    _trotterstep!(pepo, bonds[2])

    return pepo
end

